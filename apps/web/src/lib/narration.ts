'use client';

import type { GameView } from '@masoi/engine';
import { narrate, narrationClips } from '@masoi/shared';
import clipManifest from '@/generated/narration-clips.json';
import { GAME_SERVER_URL } from './api';

/**
 * Vietnamese narration.
 *  1. VieNeu-TTS through the game server (`POST /api/tts`, cached server-side) — the game's narrator voice.
 *     When it is enabled, a failing line is retried and otherwise skipped (text stays on screen):
 *     we never switch to a different (browser) voice mid-game.
 *  2. Server without TTS (e.g. production VPS): pre-recorded clips in the same VieNeu voice
 *     (public/assets/audio/narration, generated by `npm run narration:generate`). Names are not spoken.
 *  3. Last resort (no clips either): Web Speech API (vi-VN).
 *  Text is always shown on screen regardless.
 */
const CLIPS = (clipManifest as { clips: Record<string, string> }).clips;
let ttsStatus: { ok: boolean; at: number } | null = null;
let ttsStatusPending: Promise<boolean> | null = null;
let audio: HTMLAudioElement | null = null;
let controller: AbortController | null = null;
let pendingUnlock: HTMLAudioElement | null = null;
const blobCache = new Map<string, string>();
const MAX_CACHE = 40;
const NEGATIVE_TTL_MS = 10_000;

export function serverTtsAvailable(): Promise<boolean> {
  if (ttsStatus && (ttsStatus.ok || Date.now() - ttsStatus.at < NEGATIVE_TTL_MS)) return Promise.resolve(ttsStatus.ok);
  if (!ttsStatusPending) {
    ttsStatusPending = fetch(`${GAME_SERVER_URL}/api/tts/status`)
      .then((r) => (r.ok ? (r.json() as Promise<{ enabled: boolean }>) : { enabled: false }))
      .then((s) => Boolean(s.enabled))
      .catch(() => false)
      .then((ok) => {
        ttsStatus = { ok, at: Date.now() };
        ttsStatusPending = null;
        return ok;
      });
  }
  return ttsStatusPending;
}

async function fetchAudio(text: string, token: string, signal: AbortSignal): Promise<string> {
  const hit = blobCache.get(text);
  if (hit) return hit;
  const res = await fetch(`${GAME_SERVER_URL}/api/tts`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: `Bearer ${token}` },
    body: JSON.stringify({ text }),
    signal,
  });
  if (!res.ok) throw new Error(`tts ${res.status}`);
  const url = URL.createObjectURL(await res.blob());
  blobCache.set(text, url);
  if (blobCache.size > MAX_CACHE) {
    const [oldest] = blobCache.keys();
    if (oldest) {
      URL.revokeObjectURL(blobCache.get(oldest) as string);
      blobCache.delete(oldest);
    }
  }
  return url;
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Browsers may block audio until the user interacts; play the pending line on the next tap/click/key. */
function playWhenUnlocked(el: HTMLAudioElement) {
  pendingUnlock = el;
  const unlock = () => {
    const p = pendingUnlock;
    pendingUnlock = null;
    if (p && p === audio) void p.play().catch(() => undefined);
  };
  window.addEventListener('pointerdown', unlock, { once: true });
  window.addEventListener('keydown', unlock, { once: true });
}

// ---- Web Speech fallback (only when the server has no TTS) -------------------

let cachedVoice: SpeechSynthesisVoice | null | undefined;

export function speechSupported(): boolean {
  return typeof window !== 'undefined' && 'speechSynthesis' in window;
}

function vietnameseVoice(): SpeechSynthesisVoice | null {
  if (!speechSupported()) return null;
  if (cachedVoice) return cachedVoice;
  cachedVoice = window.speechSynthesis.getVoices().find((v) => v.lang?.toLowerCase().startsWith('vi')) ?? null;
  return cachedVoice;
}

function browserSpeak(text: string) {
  if (!speechSupported()) return;
  const u = new SpeechSynthesisUtterance(text);
  u.lang = 'vi-VN';
  const voice = vietnameseVoice();
  if (voice) u.voice = voice;
  u.rate = 0.95;
  u.pitch = 0.9;
  window.speechSynthesis.speak(u);
}

if (speechSupported()) {
  window.speechSynthesis.onvoiceschanged = () => {
    cachedVoice = undefined;
  };
}

// ---- public API -------------------------------------------------------------

export function stopSpeaking() {
  controller?.abort();
  controller = null;
  pendingUnlock = null;
  if (audio) {
    audio.pause();
    audio = null;
  }
  if (speechSupported()) window.speechSynthesis.cancel();
}

/** Play pre-recorded clips one after another; resolves when done or interrupted. */
async function playClips(ids: string[], signal: AbortSignal): Promise<void> {
  for (const id of ids) {
    if (signal.aborted) return;
    const el = new Audio(`/assets/audio/narration/${id}.mp3?v=${CLIPS[id]}`);
    audio = el;
    try {
      await el.play();
    } catch (err) {
      if ((err as DOMException)?.name === 'NotAllowedError') playWhenUnlocked(el);
      return;
    }
    await new Promise<void>((resolve) => {
      el.addEventListener('ended', () => resolve(), { once: true });
      el.addEventListener('error', () => resolve(), { once: true });
      signal.addEventListener('abort', () => resolve(), { once: true });
    });
  }
}

/** Narrate the current phase of a game view (live VieNeu with names → recorded clips → browser voice). */
export async function speakView(view: GameView, token?: string) {
  stopSpeaking();
  const ctrl = new AbortController();
  controller = ctrl;
  if (token && (await serverTtsAvailable())) {
    if (await speakLive(narrate(view), token, ctrl)) return;
    console.warn('[narration] live VieNeu failed; using recorded clips');
  }
  if (ctrl.signal.aborted) return;
  const clips = narrationClips(view).filter((id) => id in CLIPS);
  if (clips.length) {
    await playClips(clips, ctrl.signal);
    return;
  }
  browserSpeak(narrate(view));
}

/** Speak an arbitrary line, interrupting the previous one. */
export async function speak(text: string, token?: string) {
  stopSpeaking();
  if (!text) return;
  const ctrl = new AbortController();
  controller = ctrl;
  if (token && (await serverTtsAvailable())) {
    await speakLive(text, token, ctrl);
    return;
  }
  if (!ctrl.signal.aborted) browserSpeak(text);
}

/** Live VieNeu line (with names). Returns false when every attempt failed. */
async function speakLive(text: string, token: string, ctrl: AbortController): Promise<boolean> {
  for (let attempt = 0; attempt < 3; attempt++) {
    if (ctrl.signal.aborted) return true;
    try {
      const url = await fetchAudio(text, token, ctrl.signal);
      if (ctrl.signal.aborted) return true;
      const el = new Audio(url);
      audio = el;
      try {
        await el.play();
      } catch (err) {
        if ((err as DOMException)?.name === 'NotAllowedError') playWhenUnlocked(el);
        else throw err;
      }
      return true;
    } catch (err) {
      if (ctrl.signal.aborted) return true;
      console.warn('[narration] VieNeu line failed, retrying', err);
      await sleep(800 * (attempt + 1));
    }
  }
  return false;
}
